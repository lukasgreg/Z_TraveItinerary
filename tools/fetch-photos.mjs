// Resolves each place's `photo` search query to a Wikimedia Commons image and writes photos.js.
// Usage: node tools/fetch-photos.mjs   (re-run after adding places with a `photo` query)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
globalThis.window = {};
await import(new URL("file:///" + path.join(root, "data.js").replace(/\\/g, "/")));
const { places } = window.TRIP;

const outFile = path.join(root, "photos.js");
const existing = {};
if (fs.existsSync(outFile)) {
  const m = fs.readFileSync(outFile, "utf8").match(/=\s*(\{[\s\S]*\});?\s*$/);
  if (m) Object.assign(existing, JSON.parse(m[1]));
}

async function search(q) {
  const u = new URL("https://commons.wikimedia.org/w/api.php");
  Object.entries({
    action: "query", format: "json", generator: "search", gsrnamespace: "6",
    gsrsearch: q + " filetype:bitmap", gsrlimit: "8", prop: "imageinfo",
    iiprop: "url|extmetadata|mime", iiurlwidth: "640"
  }).forEach(([k, v]) => u.searchParams.set(k, v));
  let j;
  for (let attempt = 0; attempt < 5 && !j; attempt++) {
    await new Promise((res) => setTimeout(res, 1500 * (attempt + 1)));
    const r = await fetch(u, { headers: { "User-Agent": "tenerife-itinerary/1.0 (personal trip page)" } });
    try { j = JSON.parse(await r.text()); } catch { /* rate limited, retry */ }
  }
  if (!j) return null;
  const pages = Object.values(j?.query?.pages || {}).sort((a, b) => a.index - b.index);
  for (const p of pages) {
    const ii = p.imageinfo?.[0];
    if (!ii || ii.mime !== "image/jpeg") continue;
    const meta = ii.extmetadata || {};
    const strip = (h) => (h || "").replace(/<[^>]+>/g, "").trim();
    return {
      src: ii.thumburl, page: ii.descriptionurl,
      credit: [strip(meta.Artist?.value), strip(meta.LicenseShortName?.value)].filter(Boolean).join(" · ").slice(0, 120)
    };
  }
  return null;
}

const out = {};
for (const [id, p] of Object.entries(places)) {
  if (p.img || !p.photo) continue;
  if (existing[id] && existing[id].q === p.photo) { out[id] = existing[id]; continue; }
  const hit = await search(p.photo);
  if (hit) out[id] = { q: p.photo, ...hit };
  save();
  console.log(hit ? "ok  " : "MISS", id, "←", p.photo, hit ? hit.page.split("File:")[1] : "");
}
save();
function save() { fs.writeFileSync(outFile,
  "// Generated by tools/fetch-photos.mjs — Wikimedia Commons images per place id.\nwindow.PHOTOS = " +
  JSON.stringify(out, null, 1) + ";\n");
}
